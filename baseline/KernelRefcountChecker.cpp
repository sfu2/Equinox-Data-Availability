StringMap<ApiPair *> IncMap, DecMap;

static bool inited(false);
static std::mutex _lock;
void init() {
  std::lock_guard<std::mutex> _(_lock);
  if (inited)
    return;
  inited = true;
  for (auto &P : IncDecConfig) {
    IncMap[P.second.inc_fn] = &P.second;
    DecMap[P.second.dec_fn] = &P.second;
  }
}

ApiPair const *get_inc_spec(StringRef const name) {
  init();
  auto it = IncMap.find(name);
  if (it != IncMap.end())
    return it->getValue();
  return nullptr;
}

ApiPair const *get_dec_spec(StringRef const name) {
  init();
  auto it = DecMap.find(name);
  if (it != DecMap.end())
    return it->getValue();
  return nullptr;
}

